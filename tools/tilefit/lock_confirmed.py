"""
Turn the old human confirmations (tools/confirmed_tiles.json) into tilefit locks.

The old confirmations were made at scales 0.9-1.3, so their sizes are wrong and a
few positions too. A confirmation is locked only where the current fit agrees with
it (centres within AGREE_PX); the lock uses the fit's position at the global scale.
Where they disagree the tile is listed as disputed for the owner to settle in
review.json. Entries in review.json always win and are skipped here.

Output: tools/tilefit/confirmed_locks.json (read by solve.py next to review.json)
Usage:  python tools/tilefit/lock_confirmed.py   (after a solve.py run)
"""

import json
from pathlib import Path

from common import OUT_DIR, ROOT

HERE = Path(__file__).resolve().parent
AGREE_PX = 25


def centre_gap(old, e):
    return ((old["x"] + old["width"] / 2 - e["x"] - e["width"] / 2) ** 2
            + (old["y"] + old["height"] / 2 - e["y"] - e["height"] / 2) ** 2) ** 0.5


def main():
    fit = json.loads((OUT_DIR / "tile_fit.json").read_text())["tiles"]
    conf = json.loads((ROOT / "tools" / "confirmed_tiles.json").read_text())["tiles"]
    review_path = HERE / "review.json"
    review = json.loads(review_path.read_text(encoding="utf-8"))["tiles"] if review_path.exists() else {}

    locks, disputed, skipped = {}, {}, 0
    for name, old in sorted(conf.items()):
        if old.get("status") != "confirmed":
            continue
        if name in review:
            skipped += 1
            continue
        e = fit.get(name)
        if not e or "x" not in e or e["status"] in ("removed", "too_small"):
            disputed[name] = {"old": [old["x"], old["y"]], "reason": f"fit status {e['status'] if e else 'missing'}"}
            continue
        gap = centre_gap(old, e)
        if gap < AGREE_PX:
            locks[name] = {"verdict": "lock", "x": e["x"], "y": e["y"], "from": "old confirmation"}
        else:
            disputed[name] = {"old": [old["x"], old["y"]], "fit": [e["x"], e["y"]], "gap_px": round(gap),
                              "fit_status": e["status"]}

    out = {"_doc": ("Generated by lock_confirmed.py: old confirmations that the fit agrees with, locked at "
                    "the fit's global-scale position. 'disputed' are not locked; settle them in review.json."),
           "tiles": locks, "disputed": disputed}
    (HERE / "confirmed_locks.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"locked {len(locks)}, disputed {len(disputed)}, already in review.json {skipped}")
    for name, d in sorted(disputed.items(), key=lambda kv: -kv[1].get("gap_px", 1e9)):
        print(f"  {name:45s} {d}")


if __name__ == "__main__":
    main()
