"""
Build a small, reviewable test fixture from a Silksong save.

Usage:
    python tools/make_fixture.py <save.(dat|json)> <out.json>

Always build from the .dat when one exists: hand-edited .json dumps in
savefiles/ are not trustworthy (2aftermossmother.json is missing 55 keys).

Kept:
  - every playerData scalar (bool/int/float, strings up to 64 chars)
  - every Name/Data container and list the parsers read or will read
    (Tools, ToolEquips, ExtraToolEquips, ToolLiquids, QuestCompletionData,
    Collectables, Relics, MateriumCollected, MementosDeposited,
    EnemyJournalKillData, scenesVisited, scenesMapped, StoryEvents,
    FleasCollectedTargetOrder, scenesEncounteredBench/Cocoon)
  - sceneData.persistentBools / persistentInts entries whose ID looks like a
    collectible (see PICKUP_ID)
Dropped: markers, death position, geoRocks, NPC timers inside dicts, and all
other world-state entries (breakable walls, levers, geo deposits).
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from savelib import load_save  # noqa: E402

KEEP_STRUCTURED = {
    "Tools", "ToolEquips", "ExtraToolEquips", "ToolLiquids", "QuestCompletionData",
    "QuestRumourData", "Collectables", "Relics", "MateriumCollected", "MementosDeposited",
    "EnemyJournalKillData", "scenesVisited", "scenesMapped", "StoryEvents",
    "FleasCollectedTargetOrder", "scenesEncounteredBench", "scenesEncounteredCocoon",
}
PICKUP_ID = re.compile(
    r"Heart Piece|Silk Spool|Tool Metal|Locket|Collectable Item Pickup|Corpse Pickup|Craft Pickup|Crest|Flea|Memento|Relic|Mask Shard",
    re.IGNORECASE,
)
MAX_STRING = 64


def make_fixture(save: dict, source_name: str) -> dict:
    pd_in = save.get("playerData", {})
    pd_out = {}
    for key, value in pd_in.items():
        if key in KEEP_STRUCTURED:
            pd_out[key] = value
        elif isinstance(value, (bool, int, float)) or value is None:
            pd_out[key] = value
        elif isinstance(value, str) and len(value) <= MAX_STRING:
            pd_out[key] = value

    scene_out = {}
    for kind in ("persistentBools", "persistentInts"):
        entries = ((save.get("sceneData") or {}).get(kind) or {}).get("serializedList", [])
        kept = [e for e in entries if PICKUP_ID.search(str(e.get("ID", "")))]
        scene_out[kind] = {"serializedList": kept}

    return {
        "_fixture": {
            "source": source_name,
            "version": pd_in.get("version"),
            "note": "Generated by tools/make_fixture.py - do not hand-edit; regenerate from the .dat.",
        },
        "playerData": pd_out,
        "sceneData": scene_out,
    }


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print(__doc__.strip())
        return 2
    src, dst = Path(argv[0]), Path(argv[1])
    fixture = make_fixture(load_save(src), src.name)
    text = json.dumps(fixture, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text, encoding="utf-8", newline="\n")
    print(f"{src} -> {dst} ({len(text.encode('utf-8')) // 1024} KB, "
          f"{len(fixture['playerData'])} playerData keys, "
          f"{sum(len(v['serializedList']) for v in fixture['sceneData'].values())} scene entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
